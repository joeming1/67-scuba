-- Timeline events table — one row per event in a ticket's timeline
-- Matches the TimelineEvent interface in lib/types.ts

create table if not exists public.timeline_events (
  id           text        primary key,        -- UUID generated by app
  ticket_id    text        not null references public.tickets(id) on delete cascade,
  type         text        not null default 'update',  -- 'created' | 'assigned' | 'scheduled' | 'notification' | 'verification' | etc.
  message      text        not null,
  created_at   timestamptz not null default now()
);

create index if not exists idx_timeline_events_ticket_id on public.timeline_events (ticket_id, created_at desc);

alter table public.timeline_events enable row level security;
